module fortnum_fortsym_det3
    !! A batch loop around fortsym's det3 kernels.
    !!
    !! Generated by scripts/make_fortsym_wrappers.py. The loop is the same one
    !! the fortad and Enzyme entry points have, so what is timed is the kernel
    !! rather than three different callers.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use fortnum_generated_det3_jvp, only: fortnum_det3_jvp_kernel
    use fortnum_generated_det3_vjp, only: fortnum_det3_vjp_kernel
    implicit none
    private

    public :: det3_jvp_fortsym, det3_vjp_fortsym

contains

    subroutine det3_jvp_fortsym(n, z, dz, y, dy)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(9*n), dz(9*n)
        real(dp), intent(out) :: y, dy
        integer :: i, base
        real(dp) :: tangent
        real(dp) :: a, b, c, d, f, g, h, j, k, ta, tb, tc, td, tf, tg, th, tj, &
            tk, ba, bb, bc, bd, bf, bg, bh, bj, bk, value

        y = 0.0_dp
        dy = 0.0_dp
        do i = 1, n
            base = 9*(i - 1)
            a = z(base + 1)
            b = z(base + 2)
            c = z(base + 3)
            d = z(base + 4)
            f = z(base + 5)
            g = z(base + 6)
            h = z(base + 7)
            j = z(base + 8)
            k = z(base + 9)
            ta = dz(base + 1)
            tb = dz(base + 2)
            tc = dz(base + 3)
            td = dz(base + 4)
            tf = dz(base + 5)
            tg = dz(base + 6)
            th = dz(base + 7)
            tj = dz(base + 8)
            tk = dz(base + 9)
            call fortnum_det3_jvp_kernel(a, b, c, d, f, g, h, j, k, ta, tb, tc, &
            td, tf, tg, th, tj, tk, tangent)
            dy = dy + tangent

        end do
    end subroutine det3_jvp_fortsym

    subroutine det3_vjp_fortsym(n, z, y_b, z_b)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(9*n)
        real(dp), intent(in) :: y_b
        real(dp), intent(out) :: z_b(9*n)
        integer :: i, base
        real(dp) :: u
        real(dp) :: a, b, c, d, f, g, h, j, k, ta, tb, tc, td, tf, tg, th, tj, &
            tk, ba, bb, bc, bd, bf, bg, bh, bj, bk, value

        u = y_b
        do i = 1, n
            base = 9*(i - 1)
            a = z(base + 1)
            b = z(base + 2)
            c = z(base + 3)
            d = z(base + 4)
            f = z(base + 5)
            g = z(base + 6)
            h = z(base + 7)
            j = z(base + 8)
            k = z(base + 9)
            call fortnum_det3_vjp_kernel(a, b, c, d, f, g, h, j, k, u, ba, bb, &
            bc, bd, bf, bg, bh, bj, bk)
            z_b(base + 1) = ba
            z_b(base + 2) = bb
            z_b(base + 3) = bc
            z_b(base + 4) = bd
            z_b(base + 5) = bf
            z_b(base + 6) = bg
            z_b(base + 7) = bh
            z_b(base + 8) = bj
            z_b(base + 9) = bk
        end do
    end subroutine det3_vjp_fortsym

end module fortnum_fortsym_det3
