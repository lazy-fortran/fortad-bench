module fortnum_fortsym_multi_input_p16
    !! A batch loop around fortsym's multi_input_p16 kernels.
    !!
    !! Generated by scripts/make_fortsym_wrappers.py. The loop is the same one
    !! the fortad and Enzyme entry points have, so what is timed is the kernel
    !! rather than three different callers.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use fortnum_generated_multi_input_p16_jvp, only: fortnum_multi_input_p16_jvp_kernel
    use fortnum_generated_multi_input_p16_vjp, only: fortnum_multi_input_p16_vjp_kernel
    implicit none
    private

    public :: multi_input_p16_jvp_fortsym, multi_input_p16_vjp_fortsym

contains

    subroutine multi_input_p16_jvp_fortsym(n, z, dz, y, dy)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(16*n), dz(16*n)
        real(dp), intent(out) :: y, dy
        integer :: i, base
        real(dp) :: tangent
        real(dp) :: x1, x2, x3, x4, x5, x6, x7, x8, x9, x10, x11, x12, x13, x14, &
            x15, x16, v1, v2, v3, v4, v5, v6, v7, v8, v9, v10, v11, v12, v13, &
            v14, v15, v16, adjoint1, adjoint2, adjoint3, adjoint4, adjoint5, &
            adjoint6, adjoint7, adjoint8, adjoint9, adjoint10, adjoint11, &
            adjoint12, adjoint13, adjoint14, adjoint15, adjoint16, value

        y = 0.0_dp
        dy = 0.0_dp
        do i = 1, n
            base = 16*(i - 1)
            x1 = z(base + 1)
            x2 = z(base + 2)
            x3 = z(base + 3)
            x4 = z(base + 4)
            x5 = z(base + 5)
            x6 = z(base + 6)
            x7 = z(base + 7)
            x8 = z(base + 8)
            x9 = z(base + 9)
            x10 = z(base + 10)
            x11 = z(base + 11)
            x12 = z(base + 12)
            x13 = z(base + 13)
            x14 = z(base + 14)
            x15 = z(base + 15)
            x16 = z(base + 16)
            v1 = dz(base + 1)
            v2 = dz(base + 2)
            v3 = dz(base + 3)
            v4 = dz(base + 4)
            v5 = dz(base + 5)
            v6 = dz(base + 6)
            v7 = dz(base + 7)
            v8 = dz(base + 8)
            v9 = dz(base + 9)
            v10 = dz(base + 10)
            v11 = dz(base + 11)
            v12 = dz(base + 12)
            v13 = dz(base + 13)
            v14 = dz(base + 14)
            v15 = dz(base + 15)
            v16 = dz(base + 16)
            call fortnum_multi_input_p16_jvp_kernel(x1, x2, x3, x4, x5, x6, x7, &
            x8, x9, x10, x11, x12, x13, x14, x15, x16, v1, v2, v3, v4, v5, v6, &
            v7, v8, v9, v10, v11, v12, v13, v14, v15, v16, value, tangent)
            dy = dy + tangent
            y = y + value
        end do
    end subroutine multi_input_p16_jvp_fortsym

    subroutine multi_input_p16_vjp_fortsym(n, z, y_b, z_b)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(16*n)
        real(dp), intent(in) :: y_b
        real(dp), intent(out) :: z_b(16*n)
        integer :: i, base
        real(dp) :: u
        real(dp) :: x1, x2, x3, x4, x5, x6, x7, x8, x9, x10, x11, x12, x13, x14, &
            x15, x16, v1, v2, v3, v4, v5, v6, v7, v8, v9, v10, v11, v12, v13, &
            v14, v15, v16, adjoint1, adjoint2, adjoint3, adjoint4, adjoint5, &
            adjoint6, adjoint7, adjoint8, adjoint9, adjoint10, adjoint11, &
            adjoint12, adjoint13, adjoint14, adjoint15, adjoint16, value

        u = y_b
        do i = 1, n
            base = 16*(i - 1)
            x1 = z(base + 1)
            x2 = z(base + 2)
            x3 = z(base + 3)
            x4 = z(base + 4)
            x5 = z(base + 5)
            x6 = z(base + 6)
            x7 = z(base + 7)
            x8 = z(base + 8)
            x9 = z(base + 9)
            x10 = z(base + 10)
            x11 = z(base + 11)
            x12 = z(base + 12)
            x13 = z(base + 13)
            x14 = z(base + 14)
            x15 = z(base + 15)
            x16 = z(base + 16)
            call fortnum_multi_input_p16_vjp_kernel(x1, x2, x3, x4, x5, x6, x7, &
            x8, x9, x10, x11, x12, x13, x14, x15, x16, u, value, adjoint1, &
            adjoint2, adjoint3, adjoint4, adjoint5, adjoint6, adjoint7, adjoint8, &
            adjoint9, adjoint10, adjoint11, adjoint12, adjoint13, adjoint14, &
            adjoint15, adjoint16)
            z_b(base + 1) = adjoint1
            z_b(base + 2) = adjoint2
            z_b(base + 3) = adjoint3
            z_b(base + 4) = adjoint4
            z_b(base + 5) = adjoint5
            z_b(base + 6) = adjoint6
            z_b(base + 7) = adjoint7
            z_b(base + 8) = adjoint8
            z_b(base + 9) = adjoint9
            z_b(base + 10) = adjoint10
            z_b(base + 11) = adjoint11
            z_b(base + 12) = adjoint12
            z_b(base + 13) = adjoint13
            z_b(base + 14) = adjoint14
            z_b(base + 15) = adjoint15
            z_b(base + 16) = adjoint16
        end do
    end subroutine multi_input_p16_vjp_fortsym

end module fortnum_fortsym_multi_input_p16
