module fortnum_fortsym_det2
    !! A batch loop around fortsym's det2 kernels.
    !!
    !! Generated by scripts/make_fortsym_wrappers.py. The loop is the same one
    !! the fortad and Enzyme entry points have, so what is timed is the kernel
    !! rather than three different callers.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use fortnum_generated_det2_jvp, only: fortnum_det2_jvp_kernel
    use fortnum_generated_det2_vjp, only: fortnum_det2_vjp_kernel
    implicit none
    private

    public :: det2_jvp_fortsym, det2_vjp_fortsym

contains

    subroutine det2_jvp_fortsym(n, z, dz, y, dy)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(4*n), dz(4*n)
        real(dp), intent(out) :: y, dy
        integer :: i, base
        real(dp) :: tangent
        real(dp) :: a, b, c, d, va, vb, vc, vd, ba, bb, bc, bd, value

        y = 0.0_dp
        dy = 0.0_dp
        do i = 1, n
            base = 4*(i - 1)
            a = z(base + 1)
            b = z(base + 2)
            c = z(base + 3)
            d = z(base + 4)
            va = dz(base + 1)
            vb = dz(base + 2)
            vc = dz(base + 3)
            vd = dz(base + 4)
            call fortnum_det2_jvp_kernel(a, b, c, d, va, vb, vc, vd, tangent)
            dy = dy + tangent

        end do
    end subroutine det2_jvp_fortsym

    subroutine det2_vjp_fortsym(n, z, y_b, z_b)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(4*n)
        real(dp), intent(in) :: y_b
        real(dp), intent(out) :: z_b(4*n)
        integer :: i, base
        real(dp) :: u
        real(dp) :: a, b, c, d, va, vb, vc, vd, ba, bb, bc, bd, value

        u = y_b
        do i = 1, n
            base = 4*(i - 1)
            a = z(base + 1)
            b = z(base + 2)
            c = z(base + 3)
            d = z(base + 4)
            call fortnum_det2_vjp_kernel(a, b, c, d, u, ba, bb, bc, bd)
            z_b(base + 1) = ba
            z_b(base + 2) = bb
            z_b(base + 3) = bc
            z_b(base + 4) = bd
        end do
    end subroutine det2_vjp_fortsym

end module fortnum_fortsym_det2
