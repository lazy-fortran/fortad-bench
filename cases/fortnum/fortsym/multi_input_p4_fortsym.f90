module fortnum_fortsym_multi_input_p4
    !! A batch loop around fortsym's multi_input_p4 kernels.
    !!
    !! Generated by scripts/make_fortsym_wrappers.py. The loop is the same one
    !! the fortad and Enzyme entry points have, so what is timed is the kernel
    !! rather than three different callers.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use fortnum_generated_multi_input_p4_jvp, only: fortnum_multi_input_p4_jvp_kernel
    use fortnum_generated_multi_input_p4_vjp, only: fortnum_multi_input_p4_vjp_kernel
    implicit none
    private

    public :: multi_input_p4_jvp_fortsym, multi_input_p4_vjp_fortsym

contains

    subroutine multi_input_p4_jvp_fortsym(n, z, dz, y, dy)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(4*n), dz(4*n)
        real(dp), intent(out) :: y, dy
        integer :: i, base
        real(dp) :: tangent
        real(dp) :: x1, x2, x3, x4, v1, v2, v3, v4, adjoint1, adjoint2, adjoint3, &
            adjoint4, value

        y = 0.0_dp
        dy = 0.0_dp
        do i = 1, n
            base = 4*(i - 1)
            x1 = z(base + 1)
            x2 = z(base + 2)
            x3 = z(base + 3)
            x4 = z(base + 4)
            v1 = dz(base + 1)
            v2 = dz(base + 2)
            v3 = dz(base + 3)
            v4 = dz(base + 4)
            call fortnum_multi_input_p4_jvp_kernel(x1, x2, x3, x4, v1, v2, v3, &
            v4, value, tangent)
            dy = dy + tangent
            y = y + value
        end do
    end subroutine multi_input_p4_jvp_fortsym

    subroutine multi_input_p4_vjp_fortsym(n, z, y_b, z_b)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(4*n)
        real(dp), intent(in) :: y_b
        real(dp), intent(out) :: z_b(4*n)
        integer :: i, base
        real(dp) :: u
        real(dp) :: x1, x2, x3, x4, v1, v2, v3, v4, adjoint1, adjoint2, adjoint3, &
            adjoint4, value

        u = y_b
        do i = 1, n
            base = 4*(i - 1)
            x1 = z(base + 1)
            x2 = z(base + 2)
            x3 = z(base + 3)
            x4 = z(base + 4)
            call fortnum_multi_input_p4_vjp_kernel(x1, x2, x3, x4, u, value, &
            adjoint1, adjoint2, adjoint3, adjoint4)
            z_b(base + 1) = adjoint1
            z_b(base + 2) = adjoint2
            z_b(base + 3) = adjoint3
            z_b(base + 4) = adjoint4
        end do
    end subroutine multi_input_p4_vjp_fortsym

end module fortnum_fortsym_multi_input_p4
