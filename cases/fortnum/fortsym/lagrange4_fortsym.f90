module fortnum_fortsym_lagrange4
    !! A batch loop around fortsym's lagrange4 kernels.
    !!
    !! Generated by scripts/make_fortsym_wrappers.py. The loop is the same one
    !! the fortad and Enzyme entry points have, so what is timed is the kernel
    !! rather than three different callers.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    use fortnum_generated_lagrange4_jvp, only: fortnum_lagrange4_jvp_kernel
    use fortnum_generated_lagrange4_vjp, only: fortnum_lagrange4_vjp_kernel
    implicit none
    private

    public :: lagrange4_jvp_fortsym, lagrange4_vjp_fortsym

contains

    subroutine lagrange4_jvp_fortsym(n, z, dz, y, dy)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(5*n), dz(5*n)
        real(dp), intent(out) :: y, dy
        integer :: i, base
        real(dp) :: tangent
        real(dp) :: x, y1, y2, y3, y4, tx, ty1, ty2, ty3, ty4, adjoint_x, &
            adjoint_y1, adjoint_y2, adjoint_y3, adjoint_y4, value

        y = 0.0_dp
        dy = 0.0_dp
        do i = 1, n
            base = 5*(i - 1)
            x = z(base + 1)
            y1 = z(base + 2)
            y2 = z(base + 3)
            y3 = z(base + 4)
            y4 = z(base + 5)
            tx = dz(base + 1)
            ty1 = dz(base + 2)
            ty2 = dz(base + 3)
            ty3 = dz(base + 4)
            ty4 = dz(base + 5)
            call fortnum_lagrange4_jvp_kernel(x, y1, y2, y3, y4, tx, ty1, ty2, &
            ty3, ty4, value, tangent)
            dy = dy + tangent
            y = y + value
        end do
    end subroutine lagrange4_jvp_fortsym

    subroutine lagrange4_vjp_fortsym(n, z, y_b, z_b)
        integer, intent(in) :: n
        real(dp), intent(in) :: z(5*n)
        real(dp), intent(in) :: y_b
        real(dp), intent(out) :: z_b(5*n)
        integer :: i, base
        real(dp) :: u
        real(dp) :: x, y1, y2, y3, y4, tx, ty1, ty2, ty3, ty4, adjoint_x, &
            adjoint_y1, adjoint_y2, adjoint_y3, adjoint_y4, value

        u = y_b
        do i = 1, n
            base = 5*(i - 1)
            x = z(base + 1)
            y1 = z(base + 2)
            y2 = z(base + 3)
            y3 = z(base + 4)
            y4 = z(base + 5)
            call fortnum_lagrange4_vjp_kernel(x, y1, y2, y3, y4, u, value, &
            adjoint_x, adjoint_y1, adjoint_y2, adjoint_y3, adjoint_y4)
            z_b(base + 1) = adjoint_x
            z_b(base + 2) = adjoint_y1
            z_b(base + 3) = adjoint_y2
            z_b(base + 4) = adjoint_y3
            z_b(base + 5) = adjoint_y4
        end do
    end subroutine lagrange4_vjp_fortsym

end module fortnum_fortsym_lagrange4
