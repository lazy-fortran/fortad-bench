subroutine fci_parallel_diffusion(n, z, y) bind(C, name="fci_parallel_diffusion")
    !! fci_parallel_diffusion over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(8*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: forward_value, upper_field, backward_value, lower_field, &
        line_length, parallel_coefficient, canonical_volume, staggered_volume
    real(dp) :: lower_contribution, upper_contribution
    real(dp) :: t1

    y = 0.0_dp
    do i = 1, n
        base = 8*(i - 1)
        forward_value = z(base + 1)
        upper_field = z(base + 2)
        backward_value = z(base + 3)
        lower_field = z(base + 4)
        line_length = z(base + 5)
        parallel_coefficient = z(base + 6)
        canonical_volume = z(base + 7)
        staggered_volume = z(base + 8)
        t1 = -backward_value*lower_field + forward_value*upper_field
        lower_contribution = backward_value*parallel_coefficient*staggered_volume*t1/canonical_volume/ &
            line_length**2
        upper_contribution = -forward_value*parallel_coefficient*staggered_volume*t1/canonical_volume/ &
            line_length**2
        y = y + 1.0_dp*lower_contribution
        y = y + 2.0_dp*upper_contribution
    end do
end subroutine fci_parallel_diffusion
