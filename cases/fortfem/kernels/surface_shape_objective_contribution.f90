subroutine surface_shape_objective_contribution(n, z, y)
    !! surface_shape_objective_contribution over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(3*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: candidate, target, weight
    real(dp) :: contribution


    y = 0.0_dp
    do i = 1, n
        base = 3*(i - 1)
        candidate = z(base + 1)
        target = z(base + 2)
        weight = z(base + 3)
        contribution = weight*(candidate - target)**2*5.0000000000000000E-001_dp
        y = y + 1.0_dp*contribution
    end do
end subroutine surface_shape_objective_contribution
