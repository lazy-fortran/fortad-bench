subroutine fci_cubic_lagrange_weights(n, z, y) bind(C, name="fci_cubic_lagrange_weights")
    !! fci_cubic_lagrange_weights over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(5*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: target, node_1, node_2, node_3, node_4
    real(dp) :: weight_1, weight_2, weight_3, weight_4
    real(dp) :: t1, t2, t3, t4, t5, t6, t7, t8

    y = 0.0_dp
    do i = 1, n
        base = 5*(i - 1)
        target = z(base + 1)
        node_1 = z(base + 2)
        node_2 = z(base + 3)
        node_3 = z(base + 4)
        node_4 = z(base + 5)
        t1 = -node_2
        t2 = -node_3
        t3 = -node_4
        t4 = target - node_2
        t5 = target - node_3
        t6 = target - node_4
        t7 = -node_1
        t8 = target - node_1
        weight_1 = t4*t5*t6/(node_1 - node_2)/(node_1 - node_3)/(node_1 - node_4)
        weight_2 = t8*t5*t6/(node_2 - node_1)/(node_2 - node_3)/(node_2 - node_4)
        weight_3 = t8*t4*t6/(node_3 - node_1)/(node_3 - node_2)/(node_3 - node_4)
        weight_4 = t8*t4*t5/(node_4 - node_1)/(node_4 - node_2)/(node_4 - node_3)
        y = y + 1.0_dp*weight_1
        y = y + 2.0_dp*weight_2
        y = y + 3.0_dp*weight_3
        y = y + 4.0_dp*weight_4
    end do
end subroutine fci_cubic_lagrange_weights
