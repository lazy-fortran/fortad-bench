subroutine force_balance_product(n, z, y)
    !! force_balance_product over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(3*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: weight, test_value, force_value
    real(dp) :: contribution


    y = 0.0_dp
    do i = 1, n
        base = 3*(i - 1)
        weight = z(base + 1)
        test_value = z(base + 2)
        force_value = z(base + 3)
        contribution = force_value*test_value*weight
        y = y + 1.0_dp*contribution
    end do
end subroutine force_balance_product
