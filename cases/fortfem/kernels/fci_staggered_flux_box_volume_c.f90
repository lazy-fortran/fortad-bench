subroutine fci_staggered_flux_box_volume(n, z, y) bind(C, name="fci_staggered_flux_box_volume")
    !! fci_staggered_flux_box_volume over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(4*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: forward_flux_expansion, backward_flux_expansion, &
        base_cell_area, toroidal_field
    real(dp) :: staggered_volume


    y = 0.0_dp
    do i = 1, n
        base = 4*(i - 1)
        forward_flux_expansion = z(base + 1)
        backward_flux_expansion = z(base + 2)
        base_cell_area = z(base + 3)
        toroidal_field = z(base + 4)
        staggered_volume = base_cell_area*toroidal_field*(backward_flux_expansion + &
            forward_flux_expansion)
        y = y + 1.0_dp*staggered_volume
    end do
end subroutine fci_staggered_flux_box_volume
