subroutine regularized_surface_current(n, z, y) bind(C, name="regularized_surface_current")
    !! regularized_surface_current over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(4*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: signed_distance, sheet_current, thickness, inverse_sqrt_pi
    real(dp) :: volume_current


    y = 0.0_dp
    do i = 1, n
        base = 4*(i - 1)
        signed_distance = z(base + 1)
        sheet_current = z(base + 2)
        thickness = z(base + 3)
        inverse_sqrt_pi = z(base + 4)
        volume_current = inverse_sqrt_pi*sheet_current*exp(-signed_distance**2/thickness**2)/thickness
        y = y + 1.0_dp*volume_current
    end do
end subroutine regularized_surface_current
