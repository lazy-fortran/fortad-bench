subroutine fci_quintic_lagrange_weights(n, z, y)
    !! fci_quintic_lagrange_weights over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(7*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: target, node_1, node_2, node_3, node_4, node_5, node_6
    real(dp) :: weight_1, weight_2, weight_3, weight_4, weight_5, weight_6
    real(dp) :: t1, t2, t3, t4, t5, t6, t7, t8, t9, t10, t11, t12

    y = 0.0_dp
    do i = 1, n
        base = 7*(i - 1)
        target = z(base + 1)
        node_1 = z(base + 2)
        node_2 = z(base + 3)
        node_3 = z(base + 4)
        node_4 = z(base + 5)
        node_5 = z(base + 6)
        node_6 = z(base + 7)
        t1 = -node_2
        t2 = -node_3
        t3 = -node_4
        t4 = -node_5
        t5 = -node_6
        t6 = target - node_2
        t7 = target - node_3
        t8 = target - node_4
        t9 = target - node_5
        t10 = target - node_6
        t11 = -node_1
        t12 = target - node_1
        weight_1 = t6*t7*t8*t9*t10/(node_1 - node_2)/(node_1 - node_3)/(node_1 - node_4)/(node_1 - node_5)/(node_1 - node_6)
        weight_2 = t12*t7*t8*t9*t10/(node_2 - node_1)/(node_2 - node_3)/(node_2 - node_4)/(node_2 - node_5)/(node_2 - node_6)
        weight_3 = t12*t6*t8*t9*t10/(node_3 - node_1)/(node_3 - node_2)/(node_3 - node_4)/(node_3 - node_5)/(node_3 - node_6)
        weight_4 = t12*t6*t7*t9*t10/(node_4 - node_1)/(node_4 - node_2)/(node_4 - node_3)/(node_4 - node_5)/(node_4 - node_6)
        weight_5 = t12*t6*t7*t8*t10/(node_5 - node_1)/(node_5 - node_2)/(node_5 - node_3)/(node_5 - node_4)/(node_5 - node_6)
        weight_6 = t12*t6*t7*t8*t9/(node_6 - node_1)/(node_6 - node_2)/(node_6 - node_3)/(node_6 - node_4)/(node_6 - node_5)
        y = y + weight_1
        y = y + weight_2
        y = y + weight_3
        y = y + weight_4
        y = y + weight_5
        y = y + weight_6
    end do
end subroutine fci_quintic_lagrange_weights
