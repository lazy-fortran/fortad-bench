subroutine field_aligned_hall(n, z, y) bind(C, name="field_aligned_hall")
    !! field_aligned_hall over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(4*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: hall_coefficient, direction_1, direction_2, direction_3
    real(dp) :: hall_direction_1, hall_direction_2, hall_direction_3


    y = 0.0_dp
    do i = 1, n
        base = 4*(i - 1)
        hall_coefficient = z(base + 1)
        direction_1 = z(base + 2)
        direction_2 = z(base + 3)
        direction_3 = z(base + 4)
        hall_direction_1 = direction_1*hall_coefficient
        hall_direction_2 = direction_2*hall_coefficient
        hall_direction_3 = direction_3*hall_coefficient
        y = y + 1.0_dp*hall_direction_1
        y = y + 2.0_dp*hall_direction_2
        y = y + 3.0_dp*hall_direction_3
    end do
end subroutine field_aligned_hall
