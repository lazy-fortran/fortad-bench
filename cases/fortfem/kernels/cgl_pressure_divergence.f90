subroutine cgl_pressure_divergence(n, z, y)
    !! cgl_pressure_divergence over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(20*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: p_parallel, p_perpendicular, direction_1, direction_2, &
        direction_3, parallel_gradient_1, parallel_gradient_2, &
        parallel_gradient_3, perpendicular_gradient_1, &
        perpendicular_gradient_2, perpendicular_gradient_3, &
        direction_gradient_11, direction_gradient_12, direction_gradient_13, &
        direction_gradient_21, direction_gradient_22, direction_gradient_23, &
        direction_gradient_31, direction_gradient_32, direction_gradient_33
    real(dp) :: force_1, force_2, force_3
    real(dp) :: t1, t2, t3, t4

    y = 0.0_dp
    do i = 1, n
        base = 20*(i - 1)
        p_parallel = z(base + 1)
        p_perpendicular = z(base + 2)
        direction_1 = z(base + 3)
        direction_2 = z(base + 4)
        direction_3 = z(base + 5)
        parallel_gradient_1 = z(base + 6)
        parallel_gradient_2 = z(base + 7)
        parallel_gradient_3 = z(base + 8)
        perpendicular_gradient_1 = z(base + 9)
        perpendicular_gradient_2 = z(base + 10)
        perpendicular_gradient_3 = z(base + 11)
        direction_gradient_11 = z(base + 12)
        direction_gradient_12 = z(base + 13)
        direction_gradient_13 = z(base + 14)
        direction_gradient_21 = z(base + 15)
        direction_gradient_22 = z(base + 16)
        direction_gradient_23 = z(base + 17)
        direction_gradient_31 = z(base + 18)
        direction_gradient_32 = z(base + 19)
        direction_gradient_33 = z(base + 20)
        t1 = parallel_gradient_2 - perpendicular_gradient_2
        t2 = parallel_gradient_3 - perpendicular_gradient_3
        t3 = p_parallel - p_perpendicular
        t4 = parallel_gradient_1 - perpendicular_gradient_1
        force_1 = perpendicular_gradient_1 + direction_1*direction_2*t1 + direction_1*direction_3*t2 + &
            direction_1*direction_gradient_11*t3*2 + direction_1**2*t4 + t3*(direction_1*direction_gradient_22 + &
            direction_2*direction_gradient_12) + t3*(direction_1*direction_gradient_33 + direction_3* &
            direction_gradient_13)
        force_2 = perpendicular_gradient_2 + direction_1*direction_2*t4 + direction_2*direction_3*t2 + &
            direction_2*direction_gradient_22*t3*2 + direction_2**2*t1 + t3*(direction_1*direction_gradient_21 + &
            direction_2*direction_gradient_11) + t3*(direction_2*direction_gradient_33 + direction_3* &
            direction_gradient_23)
        force_3 = perpendicular_gradient_3 + direction_1*direction_3*t4 + direction_2*direction_3*t1 + &
            direction_3*direction_gradient_33*t3*2 + direction_3**2*t2 + t3*(direction_1*direction_gradient_31 + &
            direction_3*direction_gradient_11) + t3*(direction_2*direction_gradient_32 + direction_3* &
            direction_gradient_22)
        y = y + 1.0_dp*force_1
        y = y + 2.0_dp*force_2
        y = y + 3.0_dp*force_3
    end do
end subroutine cgl_pressure_divergence
