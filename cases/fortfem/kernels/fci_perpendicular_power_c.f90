subroutine fci_perpendicular_power(n, z, y) bind(C, name="fci_perpendicular_power")
    !! fci_perpendicular_power over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(3*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: field, action, canonical_volume
    real(dp) :: perpendicular_power


    y = 0.0_dp
    do i = 1, n
        base = 3*(i - 1)
        field = z(base + 1)
        action = z(base + 2)
        canonical_volume = z(base + 3)
        perpendicular_power = action*canonical_volume*field
        y = y + 1.0_dp*perpendicular_power
    end do
end subroutine fci_perpendicular_power
