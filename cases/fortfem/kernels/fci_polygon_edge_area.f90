subroutine fci_polygon_edge_area(n, z, y)
    !! fci_polygon_edge_area over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(4*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: x_start, y_start, x_end, y_end
    real(dp) :: edge_area


    y = 0.0_dp
    do i = 1, n
        base = 4*(i - 1)
        x_start = z(base + 1)
        y_start = z(base + 2)
        x_end = z(base + 3)
        y_end = z(base + 4)
        edge_area = (-x_end*y_start + x_start*y_end)/2.0000000000000000E+000_dp
        y = y + 1.0_dp*edge_area
    end do
end subroutine fci_polygon_edge_area
