subroutine cartesian_to_toroidal(n, z, y) bind(C, name="cartesian_to_toroidal")
    !! cartesian_to_toroidal over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(4*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: point_1, point_2, point_3, scale
    real(dp) :: eta, theta, phi
    real(dp) :: t1, t2

    y = 0.0_dp
    do i = 1, n
        base = 4*(i - 1)
        point_1 = z(base + 1)
        point_2 = z(base + 2)
        point_3 = z(base + 3)
        scale = z(base + 4)
        t1 = sqrt(point_1*point_1 + point_2*point_2)
        t2 = point_3*point_3
        eta = log(((scale + t1)**2 + t2)/((t1 - scale)**2 + t2))*5.0000000000000000E-001_dp
        theta = atan2(point_3*scale*2.0000000000000000E+000_dp, t2 - scale*scale + t1*t1)
        phi = atan2(point_2, point_1)
        y = y + 1.0_dp*eta
        y = y + 2.0_dp*theta
        y = y + 3.0_dp*phi
    end do
end subroutine cartesian_to_toroidal
