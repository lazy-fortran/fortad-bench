subroutine toroidal_vector_to_cartesian(n, z, y)
    !! toroidal_vector_to_cartesian over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(6*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: eta, theta, phi, component_1, component_2, component_3
    real(dp) :: cartesian_1, cartesian_2, cartesian_3
    real(dp) :: t1, t2, t3, t4, t5, t6, t7

    y = 0.0_dp
    do i = 1, n
        base = 6*(i - 1)
        eta = z(base + 1)
        theta = z(base + 2)
        phi = z(base + 3)
        component_1 = z(base + 4)
        component_2 = z(base + 5)
        component_3 = z(base + 6)
        t1 = cos(phi)
        t2 = cosh(eta)
        t3 = cos(theta)
        t4 = -t3*t2 + 1.0000000000000000E+000_dp
        t5 = sin(theta)
        t6 = sinh(eta)
        t7 = sin(phi)
        cartesian_1 = component_1*t1*t4/(t2 - t3) - component_2*t1*t5*t6/(t2 - t3) - component_3*t7
        cartesian_2 = component_1*t7*t4/(t2 - t3) - component_2*t7*t5*t6/(t2 - t3) + component_3*t1
        cartesian_3 = -component_1*t5*t6/(t2 - t3) - component_2*t4/(t2 - t3)
        y = y + 1.0_dp*cartesian_1
        y = y + 2.0_dp*cartesian_2
        y = y + 3.0_dp*cartesian_3
    end do
end subroutine toroidal_vector_to_cartesian
