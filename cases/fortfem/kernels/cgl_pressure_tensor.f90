subroutine cgl_pressure_tensor(n, z, y)
    !! cgl_pressure_tensor over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(5*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: p_parallel, p_perpendicular, direction_1, direction_2, &
        direction_3
    real(dp) :: pressure_11, pressure_22, pressure_33, pressure_12, &
        pressure_13, pressure_23
    real(dp) :: t1

    y = 0.0_dp
    do i = 1, n
        base = 5*(i - 1)
        p_parallel = z(base + 1)
        p_perpendicular = z(base + 2)
        direction_1 = z(base + 3)
        direction_2 = z(base + 4)
        direction_3 = z(base + 5)
        t1 = p_parallel - p_perpendicular
        pressure_11 = p_perpendicular + direction_1**2*t1
        pressure_22 = p_perpendicular + direction_2**2*t1
        pressure_33 = p_perpendicular + direction_3**2*t1
        pressure_12 = direction_1*direction_2*t1
        pressure_13 = direction_1*direction_3*t1
        pressure_23 = direction_2*direction_3*t1
        y = y + pressure_11
        y = y + pressure_22
        y = y + pressure_33
        y = y + pressure_12
        y = y + pressure_13
        y = y + pressure_23
    end do
end subroutine cgl_pressure_tensor
