subroutine helmholtz_single_layer_smooth_integrand(n, z, y)
    !! helmholtz_single_layer_smooth_integrand over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(10*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: first_point_1, first_point_2, first_point_3, second_point_1, &
        second_point_2, second_point_3, first_jacobian, second_jacobian, &
        wave_number, kernel_scale
    real(dp) :: value_real, value_imag
    real(dp) :: t1, t2, t3, t4, t5

    y = 0.0_dp
    do i = 1, n
        base = 10*(i - 1)
        first_point_1 = z(base + 1)
        first_point_2 = z(base + 2)
        first_point_3 = z(base + 3)
        second_point_1 = z(base + 4)
        second_point_2 = z(base + 5)
        second_point_3 = z(base + 6)
        first_jacobian = z(base + 7)
        second_jacobian = z(base + 8)
        wave_number = z(base + 9)
        kernel_scale = z(base + 10)
        t1 = first_point_1 - second_point_1
        t2 = first_point_2 - second_point_2
        t3 = first_point_3 - second_point_3
        t4 = sqrt(t1*t1 + t2*t2 + t3*t3)
        t5 = wave_number*t4
        value_real = first_jacobian*kernel_scale*second_jacobian*(cos(t5) - 1)/t4
        value_imag = first_jacobian*kernel_scale*second_jacobian*sin(t5)/t4
        y = y + 1.0_dp*value_real
        y = y + 2.0_dp*value_imag
    end do
end subroutine helmholtz_single_layer_smooth_integrand
