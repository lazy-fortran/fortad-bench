subroutine fci_sextic_lagrange_weights(n, z, y) bind(C, name="fci_sextic_lagrange_weights")
    !! fci_sextic_lagrange_weights over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(8*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: target, node_1, node_2, node_3, node_4, node_5, node_6, node_7
    real(dp) :: weight_1, weight_2, weight_3, weight_4, weight_5, weight_6, &
        weight_7
    real(dp) :: t1, t2, t3, t4, t5, t6, t7, t8, t9, t10, t11, t12, t13, t14

    y = 0.0_dp
    do i = 1, n
        base = 8*(i - 1)
        target = z(base + 1)
        node_1 = z(base + 2)
        node_2 = z(base + 3)
        node_3 = z(base + 4)
        node_4 = z(base + 5)
        node_5 = z(base + 6)
        node_6 = z(base + 7)
        node_7 = z(base + 8)
        t1 = -node_2
        t2 = -node_3
        t3 = -node_4
        t4 = -node_5
        t5 = -node_6
        t6 = -node_7
        t7 = target - node_2
        t8 = target - node_3
        t9 = target - node_4
        t10 = target - node_5
        t11 = target - node_6
        t12 = target - node_7
        t13 = -node_1
        t14 = target - node_1
        weight_1 = t7*t8*t9*t10*t11*t12/(node_1 - node_2)/(node_1 - node_3)/(node_1 - node_4)/(node_1 - &
            node_5)/(node_1 - node_6)/(node_1 - node_7)
        weight_2 = t14*t8*t9*t10*t11*t12/(node_2 - node_1)/(node_2 - node_3)/(node_2 - node_4)/(node_2 - &
            node_5)/(node_2 - node_6)/(node_2 - node_7)
        weight_3 = t14*t7*t9*t10*t11*t12/(node_3 - node_1)/(node_3 - node_2)/(node_3 - node_4)/(node_3 - &
            node_5)/(node_3 - node_6)/(node_3 - node_7)
        weight_4 = t14*t7*t8*t10*t11*t12/(node_4 - node_1)/(node_4 - node_2)/(node_4 - node_3)/(node_4 - &
            node_5)/(node_4 - node_6)/(node_4 - node_7)
        weight_5 = t14*t7*t8*t9*t11*t12/(node_5 - node_1)/(node_5 - node_2)/(node_5 - node_3)/(node_5 - &
            node_4)/(node_5 - node_6)/(node_5 - node_7)
        weight_6 = t14*t7*t8*t9*t10*t12/(node_6 - node_1)/(node_6 - node_2)/(node_6 - node_3)/(node_6 - &
            node_4)/(node_6 - node_5)/(node_6 - node_7)
        weight_7 = t14*t7*t8*t9*t10*t11/(node_7 - node_1)/(node_7 - node_2)/(node_7 - node_3)/(node_7 - &
            node_4)/(node_7 - node_5)/(node_7 - node_6)
        y = y + 1.0_dp*weight_1
        y = y + 2.0_dp*weight_2
        y = y + 3.0_dp*weight_3
        y = y + 4.0_dp*weight_4
        y = y + 5.0_dp*weight_5
        y = y + 6.0_dp*weight_6
        y = y + 7.0_dp*weight_7
    end do
end subroutine fci_sextic_lagrange_weights
