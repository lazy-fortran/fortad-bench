subroutine fci_parallel_flux_power(n, z, y)
    !! fci_parallel_flux_power over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(3*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: gradient, coefficient, staggered_volume
    real(dp) :: parallel_flux, parallel_power


    y = 0.0_dp
    do i = 1, n
        base = 3*(i - 1)
        gradient = z(base + 1)
        coefficient = z(base + 2)
        staggered_volume = z(base + 3)
        parallel_flux = -coefficient*gradient
        parallel_power = -coefficient*staggered_volume*gradient**2
        y = y + 1.0_dp*parallel_flux
        y = y + 2.0_dp*parallel_power
    end do
end subroutine fci_parallel_flux_power
