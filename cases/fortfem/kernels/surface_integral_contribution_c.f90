subroutine surface_integral_contribution(n, z, y) bind(C, name="surface_integral_contribution")
    !! surface_integral_contribution over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(2*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: sample, weight
    real(dp) :: contribution


    y = 0.0_dp
    do i = 1, n
        base = 2*(i - 1)
        sample = z(base + 1)
        weight = z(base + 2)
        contribution = sample*weight
        y = y + 1.0_dp*contribution
    end do
end subroutine surface_integral_contribution
