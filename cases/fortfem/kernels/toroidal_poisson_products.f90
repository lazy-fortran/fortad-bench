subroutine toroidal_poisson_products(n, z, y)
    !! toroidal_poisson_products over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(8*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: degree, order, scale, eta, theta, phi, radial, radial_derivative
    real(dp) :: harmonic, field_1, field_2, field_3, dtn_value, &
        normal_derivative
    real(dp) :: t1, t2, t3, t4, t5, t6, t7, t8

    y = 0.0_dp
    do i = 1, n
        base = 8*(i - 1)
        degree = z(base + 1)
        order = z(base + 2)
        scale = z(base + 3)
        eta = z(base + 4)
        theta = z(base + 5)
        phi = z(base + 6)
        radial = z(base + 7)
        radial_derivative = z(base + 8)
        t1 = degree*theta
        t2 = cos(t1)
        t3 = order*phi
        t4 = cos(t3)
        t5 = cosh(eta) - cos(theta)
        t6 = sqrt(t5)
        t7 = sinh(eta)
        t8 = radial_derivative*t7/radial + t7/(t5*2)
        harmonic = radial*t2*t4*t6
        field_1 = -t2*t4*t5*(radial*t7/(t6*2) + radial_derivative*t7*t6)/scale
        field_2 = -t4*t5*(-degree*radial*sin(t1)*t6 + radial*t2*sin(theta)/(t6*2))/scale
        field_3 = order*radial*t2*sin(t3)*t6*t5/(scale*t7)
        dtn_value = -t5*t8/scale
        normal_derivative = -radial*t2*t4*t6*t5*t8/scale
        y = y + 1.0_dp*harmonic
        y = y + 2.0_dp*field_1
        y = y + 3.0_dp*field_2
        y = y + 4.0_dp*field_3
        y = y + 5.0_dp*dtn_value
        y = y + 6.0_dp*normal_derivative
    end do
end subroutine toroidal_poisson_products
