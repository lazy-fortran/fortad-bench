subroutine field_aligned_flux(n, z, y)
    !! field_aligned_flux over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(8*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: parallel_coefficient, perpendicular_coefficient, direction_1, &
        direction_2, direction_3, gradient_1, gradient_2, gradient_3
    real(dp) :: flux_1, flux_2, flux_3
    real(dp) :: t1, t2

    y = 0.0_dp
    do i = 1, n
        base = 8*(i - 1)
        parallel_coefficient = z(base + 1)
        perpendicular_coefficient = z(base + 2)
        direction_1 = z(base + 3)
        direction_2 = z(base + 4)
        direction_3 = z(base + 5)
        gradient_1 = z(base + 6)
        gradient_2 = z(base + 7)
        gradient_3 = z(base + 8)
        t1 = parallel_coefficient - perpendicular_coefficient
        t2 = direction_1*gradient_1 + direction_2*gradient_2 + direction_3*gradient_3
        flux_1 = direction_1*t1*t2 + gradient_1*perpendicular_coefficient
        flux_2 = direction_2*t1*t2 + gradient_2*perpendicular_coefficient
        flux_3 = direction_3*t1*t2 + gradient_3*perpendicular_coefficient
        y = y + 1.0_dp*flux_1
        y = y + 2.0_dp*flux_2
        y = y + 3.0_dp*flux_3
    end do
end subroutine field_aligned_flux
