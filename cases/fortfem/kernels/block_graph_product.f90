subroutine block_graph_product(n, z, y)
    !! block_graph_product over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(2*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: block_value, state_value
    real(dp) :: contribution


    y = 0.0_dp
    do i = 1, n
        base = 2*(i - 1)
        block_value = z(base + 1)
        state_value = z(base + 2)
        contribution = block_value*state_value
        y = y + 1.0_dp*contribution
    end do
end subroutine block_graph_product
