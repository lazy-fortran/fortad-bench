subroutine laplace_singular_edge_potential(n, z, y)
    !! laplace_singular_edge_potential over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(9*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: point_1, point_2, point_3, first_vertex_1, first_vertex_2, &
        first_vertex_3, second_vertex_1, second_vertex_2, second_vertex_3
    real(dp) :: value
    real(dp) :: t1, t2, t3, t4, t5, t6, t7, t8, t9, t10, t11, t12, t13, t14, t15, t16, t17, t18

    y = 0.0_dp
    do i = 1, n
        base = 9*(i - 1)
        point_1 = z(base + 1)
        point_2 = z(base + 2)
        point_3 = z(base + 3)
        first_vertex_1 = z(base + 4)
        first_vertex_2 = z(base + 5)
        first_vertex_3 = z(base + 6)
        second_vertex_1 = z(base + 7)
        second_vertex_2 = z(base + 8)
        second_vertex_3 = z(base + 9)
        t1 = -point_1
        t2 = first_vertex_1 - point_1
        t3 = -point_2
        t4 = first_vertex_2 - point_2
        t5 = -point_3
        t6 = first_vertex_3 - point_3
        t7 = sqrt(t2*t2 + t4*t4 + t6*t6)
        t8 = second_vertex_1 - point_1
        t9 = second_vertex_2 - point_2
        t10 = second_vertex_3 - point_3
        t11 = sqrt(t8*t8 + t9*t9 + t10*t10)
        t12 = second_vertex_1 - point_1 - t2
        t13 = second_vertex_2 - point_2 - t4
        t14 = second_vertex_3 - point_3 - t6
        t15 = sqrt(t12*t12 + t13*t13 + t14*t14)
        t16 = t2*t9 - t4*t8
        t17 = -t2*t10 + t6*t8
        t18 = t4*t10 - t6*t9
        value = log((t7 + t11 + t15)/(t7 + t11 - t15))*sqrt(t16*t16 + t17*t17 + t18*t18)/t15
        y = y + 1.0_dp*value
    end do
end subroutine laplace_singular_edge_potential
