subroutine fci_quadratic_bezier_edge_area(n, z, y) bind(C, name="fci_quadratic_bezier_edge_area")
    !! fci_quadratic_bezier_edge_area over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_c_binding, only: c_int, dp => c_double
    implicit none
    integer(c_int), intent(in), value :: n
    real(dp), intent(in) :: z(6*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: x_start, y_start, control_x, control_y, x_end, y_end
    real(dp) :: edge_area
    real(dp) :: t1, t2, t3, t4

    y = 0.0_dp
    do i = 1, n
        base = 6*(i - 1)
        x_start = z(base + 1)
        y_start = z(base + 2)
        control_x = z(base + 3)
        control_y = z(base + 4)
        x_end = z(base + 5)
        y_end = z(base + 6)
        t1 = control_y - y_start
        t2 = y_end + y_start - control_y*2.0000000000000000E+000_dp
        t3 = control_x - x_start
        t4 = x_end + x_start - control_x*2.0000000000000000E+000_dp
        edge_area = (x_start*t1*2.0000000000000000E+000_dp + x_start*t2 - y_start*t3* &
            2.0000000000000000E+000_dp - y_start*t4 + (t3*t2*2.0000000000000000E+000_dp - t1*t4* &
            2.0000000000000000E+000_dp)/3.0000000000000000E+000_dp)*5.0000000000000000E-001_dp
        y = y + 1.0_dp*edge_area
    end do
end subroutine fci_quadratic_bezier_edge_area
