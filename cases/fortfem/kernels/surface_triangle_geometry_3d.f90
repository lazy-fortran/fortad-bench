subroutine surface_triangle_geometry_3d(n, z, y)
    !! surface_triangle_geometry_3d over a batch, its outputs summed.
    !!
    !! Generated by scripts/make_fortfem_cases.py from fortfem's extracted
    !! primal. One evaluation is far below timer resolution, and a batch is how
    !! fortfem uses these - once per cell or per quadrature point.
    use, intrinsic :: iso_fortran_env, only: dp => real64
    implicit none
    integer, intent(in) :: n
    real(dp), intent(in) :: z(11*n)
    real(dp), intent(out) :: y
    integer :: i, base
    real(dp) :: vertex_11, vertex_21, vertex_31, vertex_12, vertex_22, &
        vertex_32, vertex_13, vertex_23, vertex_33, xi, eta
    real(dp) :: point_1, point_2, point_3, jacobian, normal_1, normal_2, &
        normal_3
    real(dp) :: t1, t2, t3, t4, t5, t6, t7, t8, t9, t10, t11, t12, t13

    y = 0.0_dp
    do i = 1, n
        base = 11*(i - 1)
        vertex_11 = z(base + 1)
        vertex_21 = z(base + 2)
        vertex_31 = z(base + 3)
        vertex_12 = z(base + 4)
        vertex_22 = z(base + 5)
        vertex_32 = z(base + 6)
        vertex_13 = z(base + 7)
        vertex_23 = z(base + 8)
        vertex_33 = z(base + 9)
        xi = z(base + 10)
        eta = z(base + 11)
        t1 = -vertex_11
        t2 = vertex_13 - vertex_11
        t3 = vertex_12 - vertex_11
        t4 = -vertex_21
        t5 = vertex_23 - vertex_21
        t6 = vertex_22 - vertex_21
        t7 = -vertex_31
        t8 = vertex_33 - vertex_31
        t9 = vertex_32 - vertex_31
        t10 = t3*t5 - t2*t6
        t11 = -t3*t8 + t2*t9
        t12 = t6*t8 - t5*t9
        t13 = sqrt(t10*t10 + t11*t11 + t12*t12)
        point_1 = vertex_11 + eta*t2 + xi*t3
        point_2 = vertex_21 + eta*t5 + xi*t6
        point_3 = vertex_31 + eta*t8 + xi*t9
        jacobian = t13
        normal_1 = t12/t13
        normal_2 = t11/t13
        normal_3 = t10/t13
        y = y + point_1
        y = y + point_2
        y = y + point_3
        y = y + jacobian
        y = y + normal_1
        y = y + normal_2
        y = y + normal_3
    end do
end subroutine surface_triangle_geometry_3d
